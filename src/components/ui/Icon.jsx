/**
 * Render a lucide icon by name. Falls back to a neutral dot so a typo in a
 * data file degrades quietly instead of crashing a page.
 */
export default function Icon({ name, ...props }) {
  const Cmp = REGISTRY[name] ?? CircleDot
  return <Cmp aria-hidden="true" {...props} />
}
